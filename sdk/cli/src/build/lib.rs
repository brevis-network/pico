//! `cargo pico lib`: the Pico runtime as a static library, `libpico_zkvm.a`, beside `pico.ld`, for
//! a guest built without `cargo pico build` (zkevm-standards' static library and linker script).
//!
//! The library is `pico-sdk` compiled as a `staticlib`: `_start`, `read_input` / `write_output`,
//! the accelerators, `memcpy` / `memset` and the C failure entry points, with C ABI, and the Rust
//! standard library they are written against. A Rust guest built by `cargo pico build` links the
//! same crate, so the two kinds of guest get the same symbols.
//!
//! The crate that wraps it is generated in a cache directory, `~/.pico/lib` (or
//! `$PICO_LIB_CACHE`), and takes `pico-sdk` from this CLI's release or from `$PICO_SOURCE`, as
//! the AOT helper does.

use std::{
    env, fs,
    path::{Path, PathBuf},
};

use anyhow::{bail, Context, Result};

use super::{
    build::{create_cargo_build_command, LINKER_SCRIPT, TARGET_TRIPLE},
    execute_command,
};
use crate::source::{pico_dependency, pico_source};

/// The cache directory's override.
pub const CACHE_ENV: &str = "PICO_LIB_CACHE";

/// The library's name: `lib<LIBRARY>.a`.
const LIBRARY: &str = "pico_zkvm";

const LOCK: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../Cargo.lock"));

/// Builds the library and writes `libpico_zkvm.a` and `pico.ld` into `output`; returns the
/// library's path.
pub fn build_library(output: &Path) -> Result<PathBuf> {
    let dir = cache_root()?;
    write_crate(&dir, &pico_dependency(pico_source()?.as_deref(), "sdk/sdk"))?;

    let mut build = create_cargo_build_command("build", &[]);
    build.arg("--manifest-path").arg(dir.join("Cargo.toml"));
    execute_command(build)?;

    let archive = format!("lib{LIBRARY}.a");
    let built = dir
        .join("target")
        .join(TARGET_TRIPLE)
        .join("release")
        .join(&archive);
    if !built.is_file() {
        bail!("the build finished without `{}`", built.display());
    }
    fs::create_dir_all(output).with_context(|| format!("creating {}", output.display()))?;
    let library = output.join(&archive);
    fs::copy(&built, &library)
        .with_context(|| format!("copying {} to {}", built.display(), library.display()))?;
    let script = output.join("pico.ld");
    fs::write(&script, LINKER_SCRIPT).with_context(|| format!("writing {}", script.display()))?;
    Ok(library)
}

fn cache_root() -> Result<PathBuf> {
    let root = match env::var_os(CACHE_ENV).filter(|root| !root.is_empty()) {
        Some(root) => PathBuf::from(root),
        None => dirs::home_dir()
            .context("cannot find the home directory, where `.pico` lives")?
            .join(".pico/lib"),
    };
    std::path::absolute(&root).with_context(|| format!("{CACHE_ENV}=`{}`", root.display()))
}

/// The wrapping crate. Rewritten on every run, so that it follows `$PICO_SOURCE`; its `target`
/// stays, so a rebuild is incremental.
fn write_crate(dir: &Path, pico_sdk: &str) -> Result<()> {
    let manifest = format!(
        "[package]\nname = \"pico-zkvm\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\
         publish = false\n\n[lib]\nname = \"{LIBRARY}\"\npath = \"lib.rs\"\n\
         crate-type = [\"staticlib\"]\n\n[dependencies]\npico-sdk = {{ {pico_sdk} }}\n\n\
         # Its own workspace, so a cache inside another project is not taken for part of it.\n\
         [workspace]\n"
    );
    let lib = "//! Generated by `cargo pico lib`: `pico-sdk` as a static library.\n\
               extern crate pico_sdk;\n";
    let files = [
        ("Cargo.toml", manifest),
        ("Cargo.lock", LOCK.to_owned()),
        ("lib.rs", lib.to_owned()),
    ];
    for (name, contents) in files {
        let path = dir.join(name);
        fs::create_dir_all(dir)
            .and_then(|()| fs::write(&path, contents))
            .with_context(|| format!("cannot write `{}`", path.display()))?;
    }
    Ok(())
}
