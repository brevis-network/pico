//! Global Scheduler for distributed VM proof generation
//!
//! Runs embedded in Primary machine. Manages:
//! - Task queue (chunk proof tasks and combine tasks)
//! - Global proof tree tracking (using common ProofTree)
//! - Dynamic task assignment to workers

use crate::{
    common::machine_role::{get_runtime_mode, RuntimeMode},
    gateway::handler::proof_tree::{IndexedProof, ProofTree},
};
use parking_lot::Mutex;
use std::{
    collections::{BTreeSet, HashSet, VecDeque},
    fmt,
    sync::{
        atomic::{AtomicBool, AtomicU64, AtomicUsize, Ordering},
        Arc,
    },
    time::Duration,
};
use tokio::sync::oneshot;
use tracing::{debug, info, warn};

/// How long `acquire_task_async` waits for a task before it declares the system broken. Extended
/// from 60 s to allow slow emulation under CPU contention.
const ACQUIRE_TIMEOUT: Duration = Duration::from_secs(300);

/// How long a waiter sleeps before it checks the queues itself (see `acquire_task_async`).
const WAIT_SLICE: Duration = Duration::from_secs(1);

/// Where a test can pause a thread to force an interleaving (see the tests at the bottom).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum HookPoint {
    /// A producer found no waiter for its task and is about to queue it.
    BeforeEnqueue,
    /// A worker found no task and is about to register as a waiter.
    BeforeRegisterWaiter,
}

#[cfg(test)]
type TestHook = Arc<dyn Fn(HookPoint) + Send + Sync>;

/// A combine task: combine two adjacent proofs into one
#[derive(Clone)]
pub struct CombineTask<P> {
    pub left: IndexedProof<P>,
    pub right: IndexedProof<P>,
    /// If set, this task is preferred for a specific worker (local affinity)
    pub preferred_worker: Option<String>,
}

impl<P> fmt::Debug for CombineTask<P> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "CombineTask([{}, {}] + [{}, {}])",
            self.left.start_chunk,
            self.left.end_chunk,
            self.right.start_chunk,
            self.right.end_chunk
        )
    }
}

/// Task types that can be assigned to workers
#[derive(Clone)]
pub enum SchedulerTask<P> {
    /// Generate proof for a single chunk
    ChunkProof { chunk_idx: usize },
    /// Combine two adjacent proofs
    Combine(CombineTask<P>),
}

impl<P> fmt::Debug for SchedulerTask<P> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::ChunkProof { chunk_idx } => write!(f, "ChunkProof({})", chunk_idx),
            Self::Combine(task) => write!(f, "{:?}", task),
        }
    }
}

/// Result of acquiring a task
pub enum AcquireResult<P> {
    /// Got a task to work on
    Task(SchedulerTask<P>),
    /// No tasks available, but work not complete - wait and retry
    WaitForMore,
    /// All work complete
    Complete,
}

struct Waiter<P> {
    id: u64,
    worker_id: String,
    sender: oneshot::Sender<SchedulerTask<P>>,
}

/// What a waiter finds when its wait slice runs out (see `GlobalScheduler::recheck_queues`).
enum Recheck<P> {
    /// Still registered, and took this queued task: it is deregistered now.
    Took(SchedulerTask<P>),
    /// Still registered, and nothing is queued that it can take.
    Nothing,
    /// No longer registered: a producer sent it a task, or completion dropped its sender, so its
    /// receiver already holds the outcome.
    Resolved,
}

/// Global scheduler state
pub struct GlobalScheduler<P: Clone + Send + Sync> {
    /// Chunk indices to process (populated during emulation)
    chunk_queue: Mutex<VecDeque<usize>>,
    /// Combine tasks queue (generated by global proof tree)
    combine_queue: Mutex<VecDeque<CombineTask<P>>>,
    /// Global proof tree tracking all proofs
    /// We use ProofTree<P, P> but we don't really use the Embed part for scheduling
    proof_tree: Mutex<ProofTree<P, P>>,

    /// Min chunk index (set after emulation registration)
    min_chunk: AtomicUsize,
    /// Max chunk index (set after emulation registration)
    max_chunk: AtomicUsize,
    /// True after all chunks have been registered
    emulation_done: AtomicBool,
    /// True when final proof is complete
    completed: AtomicBool,

    /// Number of chunk proofs generated (for tracking progress)
    chunks_proven: AtomicUsize,
    /// Expected total chunks
    total_chunks: AtomicUsize,

    /// Number of proofs currently being worked on (in-flight)
    in_flight: AtomicUsize,

    /// Set of chunks already registered (to prevent duplicates)
    registered_chunks: Mutex<HashSet<usize>>,

    /// Current block number (for completion signaling)
    block_num: AtomicU64,
    /// Last completed block number (persists across reset for Secondary to detect)
    last_completed_block: AtomicU64,

    /// Waiters queue for pull workers. Matched by runtime topology.
    waiters: Mutex<VecDeque<Waiter<P>>>,
    /// Monotonic ID for waiter registration, used to safely remove a waiter after
    /// a post-registration re-check without relying on worker_id uniqueness.
    next_waiter_id: AtomicU64,

    /// Set of chunk indices that have been proven.
    /// Sent to consumers via gRPC so they can clean up RecordStore entries.
    proven_chunks: Mutex<BTreeSet<usize>>,

    /// No-combine mode: chunk proofs are terminal — no combine tasks are generated and completion
    /// is count-based (`chunks_proven == total_chunks`). Default `false` keeps the combine-tree
    /// behaviour unchanged.
    no_combine: AtomicBool,

    /// How long a waiter sleeps between its own queue checks: `WAIT_SLICE`, except in tests.
    wait_slice: Duration,

    /// Set by [`Self::abort`]: the run is being drained, so nothing more is handed out or kept.
    aborted: AtomicBool,

    #[cfg(test)]
    test_hook: Mutex<Option<TestHook>>,
}

impl<P: Clone + Send + Sync + 'static> GlobalScheduler<P> {
    pub fn new() -> Self {
        Self {
            chunk_queue: Mutex::new(VecDeque::new()),
            combine_queue: Mutex::new(VecDeque::new()),
            proof_tree: Mutex::new(ProofTree::default()),
            min_chunk: AtomicUsize::new(usize::MAX),
            max_chunk: AtomicUsize::new(0),
            emulation_done: AtomicBool::new(false),
            completed: AtomicBool::new(false),
            chunks_proven: AtomicUsize::new(0),
            total_chunks: AtomicUsize::new(0),
            in_flight: AtomicUsize::new(0),
            registered_chunks: Mutex::new(HashSet::new()),
            block_num: AtomicU64::new(0),
            last_completed_block: AtomicU64::new(0),
            waiters: Mutex::new(VecDeque::new()),
            next_waiter_id: AtomicU64::new(1),
            proven_chunks: Mutex::new(BTreeSet::new()),
            no_combine: AtomicBool::new(false),
            wait_slice: WAIT_SLICE,
            aborted: AtomicBool::new(false),
            #[cfg(test)]
            test_hook: Mutex::new(None),
        }
    }

    /// A scheduler whose waiters check the queues themselves every `wait_slice`.
    #[cfg(test)]
    fn with_wait_slice(wait_slice: Duration) -> Self {
        Self {
            wait_slice,
            ..Self::new()
        }
    }

    /// Runs the test's hook at `_at`, if one is set. Nothing outside tests.
    #[inline(always)]
    fn test_hook(&self, _at: HookPoint) {
        #[cfg(test)]
        {
            // Cloned out first: the hook may block, and must not do so holding this lock.
            let hook = self.test_hook.lock().clone();
            if let Some(hook) = hook {
                hook(_at);
            }
        }
    }

    /// Enable no-combine mode (riscv-only). Call once before scheduling starts.
    pub fn set_no_combine(&self, enabled: bool) {
        self.no_combine.store(enabled, Ordering::SeqCst);
    }

    /// Count-based completion used in no-combine mode.
    fn no_combine_complete(&self) -> bool {
        let total = self.total_chunks.load(Ordering::SeqCst);
        total > 0
            && self.emulation_done.load(Ordering::SeqCst)
            && self.in_flight.load(Ordering::SeqCst) == 0
            && self.chunk_queue.lock().is_empty()
            && self.chunks_proven.load(Ordering::SeqCst) >= total
    }

    /// Latch completion for the current block: set `completed` and record its number.
    fn mark_complete(&self) {
        self.completed.store(true, Ordering::SeqCst);
        let block = self.block_num.load(Ordering::SeqCst);
        self.last_completed_block.store(block, Ordering::SeqCst);
    }

    /// FRI_RISCV_ONLY terminal report: count a proven chunk with no proof payload and complete
    /// when all chunks are in. Mirrors the no-combine branch of `report_proof` (which drops the
    /// proof anyway) but takes no proof, so the FRI riscv `BaseProof` need not be lifted to `P`.
    pub fn report_chunk_terminal(&self, chunk_idx: usize) {
        if self.is_aborted() {
            return;
        }
        self.in_flight.fetch_sub(1, Ordering::SeqCst);
        self.chunks_proven.fetch_add(1, Ordering::SeqCst);
        self.proven_chunks.lock().insert(chunk_idx);
        if self.no_combine_complete() {
            self.completed.store(true, Ordering::SeqCst);
            let block = self.block_num.load(Ordering::SeqCst);
            self.last_completed_block.store(block, Ordering::SeqCst);
            info!(
                "GlobalScheduler(riscv-only): all chunks proven, block={}",
                block
            );
            self.wake_all_waiters_complete();
        }
    }

    /// Ends the current block without a result: waiters and later acquires get `Complete`, and
    /// chunks or proofs that still arrive are dropped, so every lane drains and exits. `reset`
    /// clears it for the next block.
    pub fn abort(&self) {
        self.aborted.store(true, Ordering::SeqCst);
        self.completed.store(true, Ordering::SeqCst);
        info!("GlobalScheduler: run aborted");
        self.wake_all_waiters_complete();
    }

    fn is_aborted(&self) -> bool {
        self.aborted.load(Ordering::SeqCst)
    }

    /// Register a chunk during emulation (called by Primary only)
    pub fn register_chunk(&self, chunk_idx: usize) {
        if self.is_aborted() {
            return;
        }
        // De-duplicate
        let mut registered = self.registered_chunks.lock();
        if registered.contains(&chunk_idx) {
            return;
        }
        registered.insert(chunk_idx);
        drop(registered);

        // Update min/max
        self.min_chunk.fetch_min(chunk_idx, Ordering::SeqCst);
        self.max_chunk.fetch_max(chunk_idx, Ordering::SeqCst);

        self.dispatch_or_enqueue(SchedulerTask::ChunkProof { chunk_idx });

        debug!("GlobalScheduler: registered chunk {}", chunk_idx);
    }

    /// Mark emulation as complete (called after all chunks registered)
    pub fn finalize_emulation(&self) {
        let min = self.min_chunk.load(Ordering::SeqCst);
        let max = self.max_chunk.load(Ordering::SeqCst);
        let total = if min <= max { max - min + 1 } else { 0 };

        self.total_chunks.store(total, Ordering::SeqCst);
        // We don't need to explicitly set range on ProofTree, it figures out completion
        // by checking if it collapsed to a single node covering the full range

        self.emulation_done.store(true, Ordering::SeqCst);

        info!(
            "GlobalScheduler: emulation finalized, chunks [{}, {}], total = {}",
            min, max, total
        );
    }

    /// Acquire next task for a worker
    /// Default (`chunk-priority` feature): Chunk tasks have priority over combine tasks
    /// Without feature: Combine tasks have priority (Legacy)
    pub fn acquire_task(&self, worker_id: &str) -> AcquireResult<P> {
        // Check if already complete
        if self.completed.load(Ordering::SeqCst) {
            return AcquireResult::Complete;
        }

        // Task priority order depends on feature flag
        #[cfg(feature = "chunk-priority")]
        {
            // Default: Chunk tasks first, then combine tasks
            if let Some(result) = self.try_acquire_chunk_task(worker_id) {
                return result;
            }
            if let Some(result) = self.try_acquire_combine_task(worker_id) {
                return result;
            }
        }
        #[cfg(not(feature = "chunk-priority"))]
        {
            // Without feature: Combine tasks first, then chunk tasks
            if let Some(result) = self.try_acquire_combine_task(worker_id) {
                return result;
            }
            if let Some(result) = self.try_acquire_chunk_task(worker_id) {
                return result;
            }
        }

        // No tasks available - check completion status
        self.check_completion_status()
    }

    /// Try to acquire from queue without locking proof_tree. Used for post-registration
    /// re-check to close queue race without lock inversion.
    fn try_acquire_queued_task_only(&self, worker_id: &str) -> Option<SchedulerTask<P>> {
        #[cfg(feature = "chunk-priority")]
        {
            if let Some(AcquireResult::Task(task)) = self.try_acquire_chunk_task(worker_id) {
                return Some(task);
            }
            if let Some(AcquireResult::Task(task)) = self.try_acquire_combine_task(worker_id) {
                return Some(task);
            }
        }
        #[cfg(not(feature = "chunk-priority"))]
        {
            if let Some(AcquireResult::Task(task)) = self.try_acquire_combine_task(worker_id) {
                return Some(task);
            }
            if let Some(AcquireResult::Task(task)) = self.try_acquire_chunk_task(worker_id) {
                return Some(task);
            }
        }

        None
    }

    /// Try to acquire a combine task
    fn try_acquire_combine_task(&self, worker_id: &str) -> Option<AcquireResult<P>> {
        let mut queue = self.combine_queue.lock();
        let runtime_mode = get_runtime_mode();
        let is_primary = runtime_mode.is_leader_worker(worker_id);

        // First pass: Check for preferred tasks or final task (Primary only)
        if let Some(pos) = queue.iter().position(|t| {
            if self.is_final_combine(t.left.start_chunk, t.right.end_chunk) {
                return is_primary;
            }
            t.preferred_worker.as_deref() == Some(worker_id)
        }) {
            let combine_task = queue.remove(pos).unwrap();
            self.in_flight.fetch_add(1, Ordering::SeqCst);
            debug!(
                "GlobalScheduler: {} acquired PREFERRED combine task [{}, {}] + [{}, {}]",
                worker_id,
                combine_task.left.start_chunk,
                combine_task.left.end_chunk,
                combine_task.right.start_chunk,
                combine_task.right.end_chunk
            );
            return Some(AcquireResult::Task(SchedulerTask::Combine(combine_task)));
        }

        // Second pass: Take any unpreferred task
        if let Some(pos) = queue.iter().position(|t| {
            if self.is_final_combine(t.left.start_chunk, t.right.end_chunk) && !is_primary {
                return false;
            }
            t.preferred_worker.is_none()
        }) {
            let combine_task = queue.remove(pos).unwrap();
            self.in_flight.fetch_add(1, Ordering::SeqCst);
            debug!(
                "GlobalScheduler: {} acquired combine task [{}, {}] + [{}, {}]",
                worker_id,
                combine_task.left.start_chunk,
                combine_task.left.end_chunk,
                combine_task.right.start_chunk,
                combine_task.right.end_chunk
            );
            return Some(AcquireResult::Task(SchedulerTask::Combine(combine_task)));
        }
        None
    }

    /// Try to acquire a chunk proof task
    fn try_acquire_chunk_task(&self, worker_id: &str) -> Option<AcquireResult<P>> {
        let runtime_mode = get_runtime_mode();
        let mut chunk_queue = self.chunk_queue.lock();
        // Single-node accepts every chunk on the same worker pool.
        let chunk_to_take = match runtime_mode {
            RuntimeMode::SingleNode => (!chunk_queue.is_empty()).then_some(0),
            RuntimeMode::TwoMachinePrimary | RuntimeMode::TwoMachineSecondary => chunk_queue
                .iter()
                .position(|&idx| runtime_mode.worker_can_handle_chunk_for_worker(worker_id, idx)),
        };

        if let Some(pos) = chunk_to_take {
            let chunk_idx = chunk_queue.remove(pos).unwrap();
            drop(chunk_queue);
            self.in_flight.fetch_add(1, Ordering::SeqCst);
            debug!(
                "GlobalScheduler: {} acquired chunk task {} (range: {})",
                worker_id,
                chunk_idx,
                if runtime_mode.is_single_node() {
                    "single-node"
                } else if runtime_mode.worker_can_handle_chunk_for_worker(worker_id, chunk_idx) {
                    "assigned"
                } else {
                    "unassigned"
                }
            );
            return Some(AcquireResult::Task(SchedulerTask::ChunkProof { chunk_idx }));
        }
        None
    }

    /// Check if work is complete or should wait
    fn check_completion_status(&self) -> AcquireResult<P> {
        // No-combine mode: completion is count-based (no proof-tree collapse).
        if self.no_combine.load(Ordering::SeqCst) {
            if self.no_combine_complete() {
                self.mark_complete();
                return AcquireResult::Complete;
            }
            return AcquireResult::WaitForMore;
        }

        let emulation_done = self.emulation_done.load(Ordering::SeqCst);
        let in_flight = self.in_flight.load(Ordering::SeqCst);
        let queue_empty =
            self.chunk_queue.lock().is_empty() && self.combine_queue.lock().is_empty();

        if emulation_done && queue_empty && in_flight == 0 && self.is_proof_tree_complete() {
            self.completed.store(true, Ordering::SeqCst);
            let block = self.block_num.load(Ordering::SeqCst);
            self.last_completed_block.store(block, Ordering::SeqCst);
            return AcquireResult::Complete;
        }

        if in_flight > 0 || !emulation_done || !queue_empty {
            debug!(
                "GlobalScheduler: WaitForMore. emulation_done={}, in_flight={}, queue_empty={}, tree_complete={}",
                emulation_done, in_flight, queue_empty, self.is_proof_tree_complete()
            );
        }

        AcquireResult::WaitForMore
    }

    /// Hand `task` to a waiting worker, or queue it, atomically with respect to waiter
    /// registration.
    ///
    /// Both steps run under the `waiters` lock. `acquire_task_async` registers a waiter and
    /// re-checks the queues under that same lock, so either the task is queued first and the
    /// re-check finds it, or the waiter is registered first and gets the task here. When the two
    /// steps were separate, a waiter could register between them: its re-check found the queues
    /// still empty, the task was then queued without waking it, and it slept out the whole
    /// timeout. A block hung that way for 300 s on 2026-10-15.
    ///
    /// Lock order: `waiters`, then a queue, as in `acquire_task_async`'s re-check. No path takes
    /// `waiters` while holding a queue lock.
    fn dispatch_or_enqueue(&self, task: SchedulerTask<P>) {
        let mut waiters = self.waiters.lock();
        if self.try_fulfill_waiters_locked(&mut waiters, &task) {
            return;
        }
        self.test_hook(HookPoint::BeforeEnqueue);
        match task {
            SchedulerTask::ChunkProof { chunk_idx } => self.chunk_queue.lock().push_back(chunk_idx),
            SchedulerTask::Combine(task) => self.combine_queue.lock().push_back(task),
        }
    }

    /// Send `task` to the first waiter that can take it, removing that waiter. Returns false if no
    /// waiter took it. The caller holds the `waiters` lock (see `dispatch_or_enqueue`).
    /// Waiters are matched by runtime topology and worker id labels.
    fn try_fulfill_waiters_locked(
        &self,
        waiters: &mut VecDeque<Waiter<P>>,
        task: &SchedulerTask<P>,
    ) -> bool {
        // Check if this is a final combine task (only Primary can handle it).
        // is_final_combine includes emulation_done guard to prevent mis-identifying
        // partial combines as final before all chunks are registered.
        let is_final = matches!(task, SchedulerTask::Combine(ref t)
            if self.is_final_combine(t.left.start_chunk, t.right.end_chunk));

        let runtime_mode = get_runtime_mode();

        // Use runtime-mode-aware chunk assignment logic
        let chunk_idx = if let SchedulerTask::ChunkProof { chunk_idx } = task {
            Some(*chunk_idx)
        } else {
            None
        };

        let mut i = 0;
        while i < waiters.len() {
            let worker_id = waiters[i].worker_id.clone();
            let can_take = match chunk_idx {
                Some(idx) => runtime_mode.worker_can_handle_chunk_for_worker(&worker_id, idx),
                None => {
                    if is_final {
                        runtime_mode.is_leader_worker(&worker_id)
                    } else {
                        true
                    }
                }
            };

            if !can_take {
                i += 1;
                continue;
            }

            let waiter = waiters.remove(i).expect("waiter index should be valid");
            self.in_flight.fetch_add(1, Ordering::SeqCst);
            match waiter.sender.send(task.clone()) {
                Ok(_) => {
                    debug!(
                        "GlobalScheduler: fulfilled waiter {} with {:?}",
                        worker_id, task
                    );
                    return true;
                }
                Err(_) => {
                    self.in_flight.fetch_sub(1, Ordering::SeqCst);
                    warn!("GlobalScheduler: waiter receiver dropped for {}", worker_id);
                    // Do not increment i because remove() shifts elements.
                }
            }
        }

        false
    }

    /// Async version of acquire_task - waits for task if none available.
    /// Uses long-polling: if no task is available, registers as a waiter and awaits.
    /// Timeout: 300s (panics if exceeded - indicates a broken system). The wait is cut into
    /// `WAIT_SLICE`s, after each of which the waiter checks the queues itself, so a task that
    /// reaches a queue without waking it costs one slice rather than the whole timeout.
    ///
    /// Returns one of four variants:
    ///   - `AcquireResult::Task(ChunkProof)`  — chunk-proof task
    ///   - `AcquireResult::Task(Combine)`     — combine task
    ///   - `AcquireResult::Complete`          — block fully proven (woken with `completed=true`)
    ///   - `AcquireResult::WaitForMore`       — woken by `scheduler.reset()` (i.e. `completed=false`)
    ///
    /// Note: `WaitForMore` is an *invariant-violation signal*, not a normal retry path.
    /// In a correctly behaving system no caller should ever observe it: the upper
    /// layers (`acquire_task_unified_async` on Primary, `SchedulerService::acquire_task`
    /// on the gRPC server that serves Secondary) both `panic!` if they receive it.
    /// See those call sites for details.
    pub async fn acquire_task_async(&self, worker_id: &str) -> AcquireResult<P> {
        // First, try to acquire a task synchronously
        match self.acquire_task(worker_id) {
            AcquireResult::Task(task) => return AcquireResult::Task(task),
            AcquireResult::Complete => {
                return AcquireResult::Complete;
            }
            AcquireResult::WaitForMore => {
                // Fall through to wait
            }
        }
        self.test_hook(HookPoint::BeforeRegisterWaiter);

        // No task available - register as waiter
        let (tx, rx) = oneshot::channel();
        let waiter_id = self.next_waiter_id.fetch_add(1, Ordering::SeqCst);
        let queued_task_after_registration = {
            let mut waiters = self.waiters.lock();
            if waiters.len() >= 64 {
                warn!("GlobalScheduler: waiters queue full (64), dropping oldest");
                waiters.pop_front();
            }
            waiters.push_back(Waiter {
                id: waiter_id,
                worker_id: worker_id.to_string(),
                sender: tx,
            });
            // Completion (or `abort`) may have woken the waiters between the first check and
            // this registration: drop our sender so the receiver resolves to `Complete` now.
            if self.completed.load(Ordering::SeqCst) {
                waiters.pop_back();
            }
            info!(
                "GlobalScheduler: {} registered as waiter (queue len={})",
                worker_id,
                waiters.len()
            );
            // Re-check queue while holding waiters lock to close race where
            // task arrives between first check and waiter registration.
            let queued_task = self.try_acquire_queued_task_only(worker_id);
            if queued_task.is_some() {
                if let Some(pos) = waiters.iter().position(|w| w.id == waiter_id) {
                    waiters.remove(pos);
                }
            }
            queued_task
        };

        if let Some(task) = queued_task_after_registration {
            return AcquireResult::Task(task);
        }

        // Wait for a task, up to ACQUIRE_TIMEOUT in all.
        let started = tokio::time::Instant::now();
        let mut rx = rx;
        loop {
            let woken = match tokio::time::timeout(self.wait_slice, &mut rx).await {
                Ok(woken) => woken,
                // A slice with no wakeup: check the queues ourselves. Every producer queues and
                // wakes as one step (`dispatch_or_enqueue`), so a task found here means some path
                // did not, and the warning is how that path gets found.
                Err(_) => match self.recheck_queues(worker_id, waiter_id) {
                    Recheck::Took(task) => {
                        warn!(
                            "GlobalScheduler: {} found {:?} queued while waiting without a wakeup",
                            worker_id, task
                        );
                        return AcquireResult::Task(task);
                    }
                    // The receiver holds the outcome: the next poll returns it.
                    Recheck::Resolved => continue,
                    Recheck::Nothing if started.elapsed() >= ACQUIRE_TIMEOUT => {
                        // Timeout - system is broken
                        panic!("GlobalScheduler: 300s timeout waiting for task - system is broken");
                    }
                    Recheck::Nothing => continue,
                },
            };
            return match woken {
                Ok(task) => AcquireResult::Task(task),
                Err(_) => {
                    // Sender dropped. Two possible causes:
                    //   (a) `wake_all_waiters_complete()` from `report_proof` after the block
                    //       was fully proven. `completed` was set to `true` *before* the wake,
                    //       so we observe `completed = true` and report `Complete`.
                    //   (b) `wake_all_waiters_complete()` from `scheduler.reset()` during a
                    //       block-to-block transition. `reset()` clears `completed` to `false`
                    //       *before* the wake, so we observe `completed = false`.
                    //
                    // Case (b) — `WaitForMore` — is an invariant-violation signal, NOT a
                    // normal retry path. Under correct sequencing no waiter should ever
                    // remain in the queue at reset time:
                    //   * Primary workers are gated by `acquire_task_unified_async`'s
                    //     `if scheduler.is_complete() return Complete` fast-path, which
                    //     fires as soon as `report_proof` flips `completed = true`.
                    //   * Secondary requests are gated by `SchedulerService::acquire_task`'s
                    //     `is_complete_for_block` / `is_complete()` pre-checks.
                    // Both upper layers therefore `panic!` on receiving `WaitForMore`,
                    // turning the broken invariant into an immediately observable crash
                    // rather than letting a `reset()` wake be silently mis-reported as
                    // block completion.
                    if self.completed.load(Ordering::SeqCst) {
                        AcquireResult::Complete
                    } else {
                        AcquireResult::WaitForMore
                    }
                }
            };
        }
    }

    /// The check a waiter makes when its slice runs out without a wakeup. Lock order as in
    /// `dispatch_or_enqueue`.
    fn recheck_queues(&self, worker_id: &str, waiter_id: u64) -> Recheck<P> {
        let mut waiters = self.waiters.lock();
        // Senders are taken out of `waiters`, to send or to drop, only under this lock.
        let Some(pos) = waiters.iter().position(|w| w.id == waiter_id) else {
            return Recheck::Resolved;
        };
        // Completed without waking this waiter: dropping its sender resolves it to `Complete`.
        if self.completed.load(Ordering::SeqCst) {
            waiters.remove(pos);
            return Recheck::Resolved;
        }
        match self.try_acquire_queued_task_only(worker_id) {
            Some(task) => {
                waiters.remove(pos);
                Recheck::Took(task)
            }
            None => Recheck::Nothing,
        }
    }

    /// Returns the combine task if a new one is generated
    pub fn report_proof(&self, proof: IndexedProof<P>, worker_id: &str) -> Option<CombineTask<P>> {
        if self.is_aborted() {
            return None;
        }
        // No-combine mode: chunk proofs are terminal. Retain the proof as a standalone leaf,
        // count it, and complete when all chunks are proven — never generate combine tasks.
        if self.no_combine.load(Ordering::SeqCst) {
            self.in_flight.fetch_sub(1, Ordering::SeqCst);
            if proof.start_chunk == proof.end_chunk {
                self.chunks_proven.fetch_add(1, Ordering::SeqCst);
                self.proven_chunks.lock().insert(proof.start_chunk);
            }
            // The proof is intentionally NOT retained: riscv-only has no combine/aggregation
            // consumer, so we drop it here (freeing the large per-chunk proof) instead of
            // accumulating every proof in the tree. Cross-chunk GCS is tracked by the caller.
            drop(proof);
            if self.no_combine_complete() {
                self.mark_complete();
                info!(
                    "GlobalScheduler(no-combine): all chunks proven, block={}",
                    self.block_num.load(Ordering::SeqCst)
                );
                self.wake_all_waiters_complete();
            }
            return None;
        }

        self.in_flight.fetch_sub(1, Ordering::SeqCst);

        debug!(
            "GlobalScheduler: {} reported proof [{}, {}]",
            worker_id, proof.start_chunk, proof.end_chunk
        );

        // Track progress
        if proof.start_chunk == proof.end_chunk {
            self.chunks_proven.fetch_add(1, Ordering::SeqCst);

            // Track individual proven chunks for cleanup
            self.proven_chunks.lock().insert(proof.start_chunk);
        }

        // Insert into global proof tree
        // The common ProofTree::set_proof returns Option<Vec<IndexedProof>> if a combine is possible
        // The index for set_proof should be the chunk index.
        // For combined proofs, we can use start_chunk as the index, similar to GlobalProofTree logic.
        // However, common ProofTree expects keys to match.
        // Let's rely on set_proof's logic: it checks adjacent nodes.
        // Note: set_proof(index, proof) inserts at index.
        // For single chunk, index = chunk_idx.
        // For combined chunk, we use start_chunk as index?
        // Let's verify common::proof_tree logic. It deletes sibling and re-inserts merged node.

        let proofs_to_combine = self
            .proof_tree
            .lock()
            .set_proof(proof.start_chunk, proof.clone());

        // If a combine task was generated, try to fulfill waiters
        if let Some(proofs) = proofs_to_combine {
            if proofs.len() == 2 {
                let combine_task = CombineTask {
                    left: proofs[0].clone(),
                    right: proofs[1].clone(),
                    preferred_worker: None,
                };
                debug!(
                    "GlobalScheduler: new combine task generated [{}, {}] + [{}, {}]",
                    combine_task.left.start_chunk,
                    combine_task.left.end_chunk,
                    combine_task.right.start_chunk,
                    combine_task.right.end_chunk
                );

                // Single source of truth: dispatch to a waiter or queue.
                // Upper layers (SchedulerService, GatewayHandler) no longer call queue_combine_task
                self.dispatch_or_enqueue(SchedulerTask::Combine(combine_task.clone()));

                return Some(combine_task);
            }
        }

        // Check completion immediately if no new task was generated (or if we fell through)
        // This ensures GatewayHandler detects completion in the same tick
        let emulation_done = self.emulation_done.load(Ordering::SeqCst);
        let in_flight = self.in_flight.load(Ordering::SeqCst);
        let queue_empty =
            self.chunk_queue.lock().is_empty() && self.combine_queue.lock().is_empty();

        if emulation_done && queue_empty && in_flight == 0 && self.is_proof_tree_complete() {
            self.completed.store(true, Ordering::SeqCst);
            // Record last completed block for Secondary to detect
            let block = self.block_num.load(Ordering::SeqCst);
            self.last_completed_block.store(block, Ordering::SeqCst);
            info!(
                "GlobalScheduler: All tasks complete (detected in report_proof), block={}",
                block
            );
            // Wake all waiters so they don't wait 300s timeout
            self.wake_all_waiters_complete();
        }

        None
    }

    /// Add a combine task: to a waiting worker if there is one, to the queue otherwise. Queueing
    /// alone would leave a waiter asleep (see `dispatch_or_enqueue`).
    pub fn queue_combine_task(&self, task: CombineTask<P>) {
        self.dispatch_or_enqueue(SchedulerTask::Combine(task));
    }

    /// Check if all work is complete
    pub fn is_complete(&self) -> bool {
        self.completed.load(Ordering::SeqCst)
    }

    /// Helper to check if proof tree is complete covering full range.
    /// Requires `emulation_done` — without it, `max_chunk` may not yet reflect the
    /// true total number of chunks.
    pub fn is_proof_tree_complete(&self) -> bool {
        if !self.emulation_done.load(Ordering::SeqCst) {
            return false;
        }

        let tree = self.proof_tree.lock();

        // Complete only when the tree collapsed to a single proved node
        if let Some((start, end)) = tree.get_single_proved_range() {
            let min = self.min_chunk.load(Ordering::SeqCst);
            let max = self.max_chunk.load(Ordering::SeqCst);
            return start == min && end == max;
        }

        false
    }

    /// Check if a combine task with given range will produce the final proof.
    /// Returns false until emulation is finalized, because `max_chunk` is updated
    /// incrementally during emulation and a combine tree that races ahead could
    /// otherwise be incorrectly flagged as final.
    pub fn is_final_combine(&self, start: usize, end: usize) -> bool {
        if !self.emulation_done.load(Ordering::SeqCst) {
            return false;
        }
        let min = self.min_chunk.load(Ordering::SeqCst);
        let max = self.max_chunk.load(Ordering::SeqCst);
        start == min && end == max
    }

    /// Wake all waiters by dropping their senders.
    /// Completed waiters will observe `AcquireResult::Complete`; reset / cleanup
    /// paths will observe `AcquireResult::WaitForMore` and retry.
    fn wake_all_waiters_complete(&self) {
        let mut waiters = self.waiters.lock();
        let count = waiters.len();
        if count > 0 {
            info!("GlobalScheduler: waking {} waiters on completion", count);
        }
        // Drop all senders - receivers will get Err which maps to AcquireResult::Complete.
        waiters.clear();
    }

    /// Set the block number for this scheduling session
    pub fn set_block_num(&self, block: u64) {
        self.block_num.store(block, Ordering::SeqCst);
    }

    /// Get the current block number
    pub fn get_block_num(&self) -> u64 {
        self.block_num.load(Ordering::SeqCst)
    }

    /// Get the final proof if complete
    pub fn final_proof(&self) -> Option<Arc<P>> {
        if self.is_complete() {
            let tree = self.proof_tree.lock();
            // riscv-only / no-combine completions (e.g. FRI_RISCV_ONLY) never populate
            // the proof tree, so it stays empty. Only extract the collapsed combine proof
            // when the inner tree has actually reduced to a single proved node; otherwise
            // there is no final proof (return None instead of tripping final_combine_proof's
            // assert). Use the inner-tree predicate (not ProofTree::len(), which also counts
            // `embed`): with an embed present + inner tree == 1, ProofTree::len() would be 2
            // and this guard would wrongly return None for a real combine proof.
            if tree.get_single_proved_range().is_some() {
                tree.final_combine_proof()
            } else {
                None
            }
        } else {
            None
        }
    }

    /// Check if emulation has been finalized
    pub fn is_emulation_done(&self) -> bool {
        self.emulation_done.load(Ordering::SeqCst)
    }

    /// True once no further chunk task can ever be dispatched: emulation has registered them all
    /// and the queue has handed the last one out. Chunks already in flight do not count -- this is
    /// about the feed, not about what is still being proven.
    pub fn chunk_feed_closed(&self) -> bool {
        self.is_aborted()
            || (self.emulation_done.load(Ordering::SeqCst) && self.chunk_queue.lock().is_empty())
    }

    /// Check if a specific block is complete
    /// Used by Secondary to detect completion even after Primary has reset
    pub fn is_complete_for_block(&self, block: u64) -> bool {
        self.last_completed_block.load(Ordering::SeqCst) == block
    }

    /// Returns true when the scheduler still has live state for the current
    /// block and should not accept a new block request.
    pub fn has_active_block(&self) -> bool {
        self.emulation_done.load(Ordering::SeqCst)
            || self.in_flight.load(Ordering::SeqCst) > 0
            || !self.chunk_queue.lock().is_empty()
            || !self.combine_queue.lock().is_empty()
            || !self.registered_chunks.lock().is_empty()
            || !self.proof_tree.lock().is_empty()
    }

    /// Get the last completed block number
    pub fn get_last_completed_block(&self) -> u64 {
        self.last_completed_block.load(Ordering::SeqCst)
    }

    /// Get current progress stats
    pub fn get_stats(&self) -> SchedulerStats {
        SchedulerStats {
            total_chunks: self.total_chunks.load(Ordering::SeqCst),
            chunks_proven: self.chunks_proven.load(Ordering::SeqCst),
            chunk_queue_len: self.chunk_queue.lock().len(),
            combine_queue_len: self.combine_queue.lock().len(),
            proof_tree_len: self.proof_tree.lock().len(),
            in_flight: self.in_flight.load(Ordering::SeqCst),
            completed: self.completed.load(Ordering::SeqCst),
        }
    }

    /// Reset scheduler for next block
    pub fn reset(&self) {
        self.chunk_queue.lock().clear();
        self.combine_queue.lock().clear();
        self.registered_chunks.lock().clear();
        // ProofTree default has empty maps
        *self.proof_tree.lock() = ProofTree::default();
        self.min_chunk.store(usize::MAX, Ordering::SeqCst);
        self.max_chunk.store(0, Ordering::SeqCst);
        self.emulation_done.store(false, Ordering::SeqCst);
        self.completed.store(false, Ordering::SeqCst);
        self.chunks_proven.store(0, Ordering::SeqCst);
        self.total_chunks.store(0, Ordering::SeqCst);
        self.in_flight.store(0, Ordering::SeqCst);
        self.aborted.store(false, Ordering::SeqCst);
        // Waiters must already be drained: report_proof's wake_all_waiters_complete()
        // empties the queue at block completion, and entry checks (`is_complete` /
        // `is_complete_for_block`) reject new acquires until the next block starts.
        // A non-empty queue here means a waiter slipped past those gates.
        {
            let waiters = self.waiters.lock();
            assert!(
                waiters.is_empty(),
                "reset(): waiters non-empty (len={}); waiter slipped past completion checks",
                waiters.len()
            );
        }
        self.proven_chunks.lock().clear();
    }

    /// Get the set of chunk indices that have been proven.
    /// Sent to consumers via gRPC so they can clean up RecordStore entries.
    pub fn get_proven_chunks(&self) -> Vec<usize> {
        self.proven_chunks.lock().iter().copied().collect()
    }

    /// Dump state for debugging
    pub fn dump_state(&self) {
        let stats = self.get_stats();
        // ProofTree implements Display, so we can format it directly
        let tree = self.proof_tree.lock();
        info!(
            "GlobalScheduler State:\n  {:?}\n  ProofTree:\n{}",
            stats, tree
        );
    }
}

impl<P: Clone + Send + Sync + 'static> Default for GlobalScheduler<P> {
    fn default() -> Self {
        Self::new()
    }
}

