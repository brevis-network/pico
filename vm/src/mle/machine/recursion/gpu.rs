//! GPU-side proving-key assembly for the MLE recursion machines (Convert / Combine).
//!
//! The HOST keygen is the reference for the vk — constraints, geometry and `vk_pre_hash` all come
//! from it — while the chips' `gpu_generate_preprocessed` plus the device `stacked_commit` build
//! the key the GPU prover actually proves with.
//!
//! The merged-preprocessed COMMITMENT, however, is the device's alone. It used to be computed on
//! both sides and welded by a digest assert, which meant every keygen paid a CPU RS-encode plus a
//! full Poseidon2 Merkle tree over the stacked preprocessed matrix whose entire surviving output
//! was a digest to compare. The host half is now skipped by default
//! ([`keygen_crosscheck_enabled`]); what the assert protected is preserved two ways:
//!
//! - [`cuda_mle::data_transporter::assemble_pk_with_device_merged_prep`] checks per-AIR presence,
//!   height and width against the host keygen's declared geometry on every call, which is the
//!   tripwire on device preprocessed generation, and installs the device root into the host key so
//!   the two cannot drift.
//! - `MLE_KEYGEN_CROSSCHECK=1` restores the host commit and the full digest equality assert. It is
//!   default-on under `cfg(test)`, so the `test_keygen_recursion_gpu_*` parity tests always exercise
//!   it — but note those tests are not run by CI (`rust.yml` is `ubuntu-latest`, and its `lint-gpu`
//!   job is clippy with `cuda-mle` excluded), so the cross-check only fires when someone runs the
//!   GPU tests by hand.
//!
//! Soundness note: the commitment is the recursion program's identity, and merged mode
//! structurally excludes commitment VALUES from the vk pre-hash preimage, so which side computes
//! it cannot change `vk_pre_hash`. Under `vk_verification` the value is pinned in-circuit against
//! the whitelist, so a divergence fails closed rather than open.
//!
//! ⚠️ That "fails closed" rests on a premise outside this file: the whitelist must be generated by
//! a keygen that still computes the host commit. It is — `scripts/src/bin/build_vk_map.rs` builds
//! it with the CPU `ConvertMachine` — which is what makes the vk_map an INDEPENDENT reference for
//! the device root, and is the last content-level check on device preprocessed generation once the
//! per-keygen host commit is gone (the geometry guard below validates shape, not values). Moving
//! vk_map generation onto a GPU machine would make the whitelist self-consistent with whatever the
//! device produced and silently void this argument; keep it on the committing path, or restore the
//! cross-check by default.

