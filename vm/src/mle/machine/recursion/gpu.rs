/// Whether to also run the host stacked commit and assert it equals the device root. Off by
/// default (the host commit is duplicate work — see the module header); on under `cfg(test)` so
/// the parity tests always exercise it, and settable with `MLE_KEYGEN_CROSSCHECK=1`.
fn keygen_crosscheck_enabled() -> bool {
    cfg!(test)
        || std::env::var("MLE_KEYGEN_CROSSCHECK")
            .map(|v| v != "0" && !v.is_empty())
            .unwrap_or(false)
}

/// The concrete GPU engine / backend the recursion provers use. Named here (rather than through
/// the module-level `Engine` alias) so this file stays valid while the alias is still CPU-typed.
pub type GpuEngineKb = cuda_mle::KoalaBearPoseidon2GpuEngine;
pub type GpuPbKb = cuda_mle::GenericGpuBackend<cuda_mle::hash_scheme::KoalaBearPoseidon2HashScheme>;

/// Bridge one chip's GPU-generated trace (row-major pool allocation) to a col-major cuda-mle
/// [`DeviceMatrix`]. The pool allocation is parked in `live` — the caller must keep it alive until
/// the per-thread stream is synchronized (the transpose reads it asynchronously).
pub(crate) fn trace_to_col_major<'a>(
    trace: TraceData<'a, Kb>,
    live: &mut Vec<DevicePoolAllocation<'a, Kb>>,
) -> DeviceMatrix<Kb> {
    let h = trace.height();
    let w = trace.width();
    match trace {
        TraceData::Gpu(_, alloc) => {
            // Borrow the pool allocation as a cuda-mle DeviceBuffer (ManuallyDrop: the buffer must
            // not free a pointer it does not own).
            let input = ManuallyDrop::new(unsafe {
                DeviceBuffer::from_raw_parts(alloc.as_ptr() as *mut Kb, h * w)
            });
            let output = DeviceBuffer::<Kb>::with_capacity(h * w);
            unsafe {
                cuda_mle::matrix_transpose_fp_any(&output, &input, w, h)
                    .expect("row-major → col-major transpose failed");
            }
            live.push(alloc);
            DeviceMatrix::new(Arc::new(output), h, w)
        }
        TraceData::Cpu(m) => {
            // Defensive fallback only — every recursion chip has a real GPU generator.
            cuda_mle::data_transporter::transport_matrix_h2d_row_major(&m)
                .expect("CPU-fallback preprocessed H2D failed")
        }
        TraceData::Debug(..) => unreachable!("debug trace variant in production path"),
    }
}

/// Keygen a recursion program for the GPU prover: host reference keygen (vk + commitment source of
/// truth) plus a device key assembled from the chips' GPU-generated preprocessed traces and a
/// device stacked commit, digest-checked against the host commitment.
///
/// Program-agnostic: every recursion machine (Convert, Combine, and a future Compress) keygens
/// through here. `chips` must be the caller's `mle_recursion_chips()` set — passed in rather than
/// built here so a machine that keygens repeatedly (per-shape) reuses its own cached set.
///
/// The host proving key is *not* returned: it exists only to carry the vk and to receive the device
/// root, and no prover on this path uses it. [`keygen_recursion_gpu_with`] hands it back for the
/// parity tests, which compare against it.
pub fn keygen_recursion_gpu(
    engine: &GpuEngineKb,
    program: &Arc<RecursionProgram<Kb>>,
    chips: &[MetaChip<Kb, RecursionChipType<Kb>>],
    device_id: usize,
) -> (
    MultiStarkVerifyingKey<Sc>,
    DeviceMultiStarkProvingKey<GpuPbKb>,
) {
    let (_host_pk, vk, device_pk) = keygen_recursion_gpu_with(
        engine,
        program,
        chips,
        device_id,
        keygen_crosscheck_enabled(),
    );
    (vk, device_pk)
}

/// [`keygen_recursion_gpu`] with the host-commit cross-check forced either way, and the host
/// proving key returned. Exists so the parity tests can drive both paths in one process without
/// racing on the env var.
pub fn keygen_recursion_gpu_with(
    engine: &GpuEngineKb,
    program: &Arc<RecursionProgram<Kb>>,
    chips: &[MetaChip<Kb, RecursionChipType<Kb>>],
    device_id: usize,
    crosscheck: bool,
) -> (
    MultiStarkProvingKey<Sc>,
    MultiStarkVerifyingKey<Sc>,
    DeviceMultiStarkProvingKey<GpuPbKb>,
) {
    // Host reference keygen: identical to the CPU proving path's keys. `air_refs_ms` stays split
    // out as the AIR-list construction cost; it is now an `Arc` bump per chip rather than a deep
    // copy of the program (see `recursion_air_refs_with_preprocessed`).
    //
    // The host commit is skipped by default: it RS-encodes and Merkle-hashes the same preprocessed
    // traces the GPU commits below, and its only surviving output was a digest to compare against
    // the device's. `assemble_pk_with_device_merged_prep` keeps the structural tripwire (per-AIR
    // presence, height and width) unconditionally, and installs the device root into the key.
    // `MLE_KEYGEN_CROSSCHECK=1` restores the full host commit and the digest equality assert.
    let t_host = Instant::now();
    let airs = recursion_air_refs_with_preprocessed(program);
    let air_refs_ms = t_host.elapsed().as_millis();
    let mut host_pk = if crosscheck {
        engine.keygen_merged_preprocessed(&airs).0
    } else {
        engine.keygen_merged_preprocessed_deferred_commit(&airs)
    };
    let host_ms = t_host.elapsed().as_millis();

    // Device preprocessed generation. The chips enqueue onto this thread's pico stream without
    // syncing; the cuda-mle transposes below run on `cudaStreamPerThread`, which is a different
    // stream — order the two explicitly with one pico-stream sync in between.
    //
    // Two classifying passes over `instructions` first, so that no chip re-scans the whole program:
    // the 7 chips shared with the FRI set read `InstructionBuckets`, and the 14 MLE-only ones read
    // `MleInstructionBuckets`. Worth doing because the loop below, not the device, is what
    // `prep_gen_ms` is made of — 23.5 ms/chunk against a 0.02 ms/chunk sync, see `prep_sync_us`.
    // Two passes rather than one because `InstructionBuckets` cannot be extended: it is
    // `Serialize`d into `program_cache.bin` over a codec that is not self-describing, so new
    // fields there would break every existing cache file.
    let t_dev = Instant::now();
    let buckets = program.bucket_for_pass();
    let bucket_us = t_dev.elapsed().as_micros();
    let traces: Vec<Option<TraceData<'_, Kb>>> = chips
        .iter()
        .map(|chip| chip.gpu_generate_preprocessed(device_id, program))
        .collect();
    // Splits `prep_gen_ms` into the serial CPU bucket+filter+enqueue loop and the trailing wait for
    // the device to drain it. Which side dominates decides whether pre-bucketing can move wall
    // clock at all: if the sync dominated, prep generation would be device-bound and a cheaper scan
    // would buy nothing. It does not — 23.5 ms/chunk loop against 0.02 ms/chunk sync.
    let prep_loop_us = t_dev.elapsed().as_micros();
    get_global_stream_pool(device_id)
        .0
        .synchronize()
        .expect("pico stream sync after preprocessed generation");
    // Includes the sync, so this is real device time rather than enqueue time.
    let prep_gen_ms = t_dev.elapsed().as_millis();
    let prep_sync_us = t_dev.elapsed().as_micros() - prep_loop_us;
    // The buckets are position lists, never a DMA source (what each chip uploads is its own local
    // copy of the matching instructions), so releasing them is not ordered against the stream.
    // Dropped here rather than at end of scope only to keep the whole prep phase in one place.
    drop(buckets);

    let t_transpose = Instant::now();
    let mut live = Vec::new();
    let per_air_prep: Vec<Option<DeviceMatrix<Kb>>> = traces
        .into_iter()
        .map(|t| t.map(|t| trace_to_col_major(t, &mut live)))
        .collect();
    let transpose_ms = t_transpose.elapsed().as_millis();

    // The device commit plus `AirDataGpu::new` for all 21 AIRs (rules, monomial expansion, JIT
    // source emission, H2D) — the two are separated inside cuda-mle, not here.
    let t_assemble = Instant::now();
    let device_pk = cuda_mle::data_transporter::assemble_pk_with_device_merged_prep::<
        cuda_mle::hash_scheme::KoalaBearPoseidon2HashScheme,
    >(engine.device(), &mut host_pk, per_air_prep)
    .expect("device merged-preprocessed key assembly failed");
    let assemble_ms = t_assemble.elapsed().as_millis();
    // Safe to release the pool allocations: the assembly synchronized the per-thread stream.
    drop(live);

    // Only valid after assembly installed the device root — before it, the deferred key still
    // carries the placeholder commitment.
    let host_vk = host_pk.get_vk();

    // Read at the same point as before, so the published span keeps its meaning and the
    // convert-stages figures stay comparable.
    let device_ms = t_dev.elapsed().as_millis();

    // Dropped explicitly, and timed, because this was 4.03 ms/chunk back when the function
    // deep-cloned the program and `airs` held the last handle to the copy. Now that the caller's
    // `Arc` outlives it, it is 21 refcount decrements — and the bracket is what keeps it that way.
    let t_drop_airs = Instant::now();
    drop(airs);
    let drop_airs_us = t_drop_airs.elapsed().as_micros();

    // `host_ms`/`device_ms` keep their published spans so the convert-stages figures stay
    // comparable; the sub-splits are additive fields, appended never inserted.
    info!(
        "mle_keygen_detail(gpu): host_ms = {host_ms}, device_ms = {device_ms}, \
         air_refs_ms = {air_refs_ms}, prep_gen_ms = {prep_gen_ms}, \
         transpose_ms = {transpose_ms}, assemble_ms = {assemble_ms}, \
         prep_loop_us = {prep_loop_us}, prep_sync_us = {prep_sync_us}, \
         drop_airs_us = {drop_airs_us}, bucket_us = {bucket_us}"
    );
    (host_pk, host_vk, device_pk)
}

/// Build a GPU proving context from a recursion record: one device main trace per chip (in
/// `mle_recursion_chips()` order), all generated by the chips' `gpu_generate_main`. The GPU
/// sibling of [`build_proving_ctx`] — same shape, no GLOBAL/GCS handling (the recursion machine
/// has none); preprocessed comes from the device pk (keygen), not from here.
pub fn build_ctx_gpu(
    record: &RecursionRecord<Kb>,
    chips: &[MetaChip<Kb, RecursionChipType<Kb>>],
    device_id: usize,
    role: &str,
) -> ProvingContext<GpuPbKb> {
    let pvs: Vec<Kb> = record.public_values.as_array().to_vec();
    let mut live = Vec::new();
    let per_trace: Vec<(usize, AirProvingContext<GpuPbKb>)> = chips
        .iter()
        .enumerate()
        .map(|(air_id, chip)| {
            // gpu_generate_main synchronizes internally (private NON_BLOCKING stream + swap +
            // syncs), so the transpose below can read the allocation immediately.
            let trace =
                chip.gpu_generate_main(device_id, record, &mut RecursionRecord::<Kb>::default());
            let matrix = trace_to_col_major(trace, &mut live);
            let ctx = if chip.name() == "PublicValues" {
                AirProvingContext::simple(matrix, pvs.clone())
            } else {
                AirProvingContext::simple_no_pis(matrix)
            };
            (air_id, ctx)
        })
        .collect();
    // One sync covers all transposes; after it the chips' pool allocations can be released.
    cuda_mle::runtime::stream::current_stream_sync()
        .expect("sync after recursion GPU trace bridge");
    drop(live);
    // Height observability, format-aligned with the CPU `build_proving_ctx` line.
    info!(
        "recursion_heights[{role}]: {}",
        chips
            .iter()
            .zip(per_trace.iter())
            .map(|(chip, (_, ctx))| format!("{}={}", chip.name(), ctx.common_main.height()))
            .collect::<Vec<_>>()
            .join(" ")
    );
    ProvingContext::new(per_trace)
}

/// Loose integration net (env-gated by the caller): rebuild the context on the CPU and require the
/// GPU context to match element-wise — every main trace, every public value.
pub fn assert_ctx_matches_cpu(
    gpu_ctx: &ProvingContext<GpuPbKb>,
    record: &RecursionRecord<Kb>,
    chips: &[MetaChip<Kb, RecursionChipType<Kb>>],
) {
    let cpu_ctx = build_proving_ctx::<Sc>(record, chips, "trace-compare");
    assert_eq!(cpu_ctx.per_trace.len(), gpu_ctx.per_trace.len());
    for ((cpu_id, cpu_air), (gpu_id, gpu_air)) in
        cpu_ctx.per_trace.iter().zip(gpu_ctx.per_trace.iter())
    {
        assert_eq!(cpu_id, gpu_id);
        let host = cuda_mle::data_transporter::transport_matrix_d2h_row_major(&gpu_air.common_main)
            .expect("trace-compare D2H failed");
        assert_eq!(
            cpu_air.common_main.values, host.values,
            "recursion GPU main trace diverges from CPU for air {cpu_id}"
        );
        assert_eq!(
            cpu_air.public_values, gpu_air.public_values,
            "recursion GPU public values diverge from CPU for air {cpu_id}"
        );
    }
    info!("recursion trace-compare: GPU context matches CPU element-wise");
}

/// GPU trace-gen must produce a device key byte-equivalent to the host keygen (the internal digest
/// assert). KoalaBear-only; needs a CUDA device.
#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        compiler::recursion::{
            instruction::{commit_public_values, Instruction},
            program::RecursionProgram,
            types::{Address, AssertZeroExtInstr},
        },
        emulator::recursion::public_values::RecursionPublicValues,
        mle::machine::riscv::{init_mle_gpu_pool, MLE_GPU_DEVICE},
    };
    use p3_field::PrimeCharacteristicRing;
    use pico_mle_core::config::recursion_params_with_100_bits_security;

    fn ensure_gpu_pools() {
        if !cuda_mle::runtime::memory_manager::external_pool_is_set(MLE_GPU_DEVICE) {
            init_mle_gpu_pool(MLE_GPU_DEVICE);
        }
    }

    /// A minimal keygen-able program: n AssertZeroExt rows plus the one CommitPublicValues every
    /// real recursion program carries (the PublicValues chip requires exactly one).
    fn sample_program(n: u32) -> RecursionProgram<Kb> {
        let mut instructions: Vec<Instruction<Kb>> = (0..n)
            .map(|i| {
                Instruction::AssertZeroExt(AssertZeroExtInstr {
                    addr: Address(Kb::from_u32(i)),
                })
            })
            .collect();
        instructions.push(commit_public_values(
            &RecursionPublicValues::<u32>::default(),
        ));
        RecursionProgram {
            instructions,
            ..Default::default()
        }
    }

    fn assert_keygen_parity(program: &Arc<RecursionProgram<Kb>>) {
        ensure_gpu_pools();
        let engine = GpuEngineKb::new(recursion_params_with_100_bits_security());
        let chips = RecursionChipType::<Kb>::mle_recursion_chips();
        // With the cross-check on, the host also commits and the GPU==CPU digest assert fires
        // inside if the device commit diverges.
        let (host_pk, host_vk, device_pk) =
            keygen_recursion_gpu_with(&engine, program, &chips, MLE_GPU_DEVICE, true);

        assert_eq!(device_pk.per_air.len(), host_pk.per_air.len());
        assert!(device_pk.merged_preprocessed.is_some());
        for (d, h) in device_pk.per_air.iter().zip(&host_pk.per_air) {
            assert_eq!(
                d.preprocessed_data.is_some(),
                h.vk.preprocessed_data.is_some(),
                "presence mismatch for {}",
                d.air_name
            );
        }
        // The returned vk equals an independent host keygen (guards accidental mutation of the
        // reference path).
        let airs = recursion_air_refs_with_preprocessed(program);
        let (_, vk2) = engine.keygen_merged_preprocessed(&airs);
        let a = bincode::serialize(&host_vk).unwrap();
        let b = bincode::serialize(&vk2).unwrap();
        assert_eq!(a, b, "host vk not reproducible");

        // The production path skips the host commit and takes the device root instead. It must
        // land on the identical vk — this is the gate on dropping the host commit at all, and it
        // is the real 21-chip AIR set rather than a fixture.
        let (_, deferred_vk, deferred_device_pk) =
            keygen_recursion_gpu_with(&engine, program, &chips, MLE_GPU_DEVICE, false);
        assert_eq!(
            bincode::serialize(&deferred_vk).unwrap(),
            a,
            "deferred-commit keygen produced a different vk than the cross-checked one"
        );
        assert_eq!(
            deferred_device_pk.merged_preprocessed.as_ref().map(|m| m.0),
            device_pk.merged_preprocessed.as_ref().map(|m| m.0),
            "device merged root is not reproducible across keygens"
        );
    }

    #[test]
    fn test_keygen_recursion_gpu_min_program_matches_host() {
        assert_keygen_parity(&Arc::new(sample_program(0)));
    }

    /// The parity above runs `sample_program`, which carries exactly one of the 14 MLE-only
    /// instruction variants — so on its own it leaves 13 device preprocessed generators
    /// unwitnessed by the host↔device digest comparison. `mixed_program` carries every declared
    /// chip's instruction at a nonzero row count, which makes this the differential oracle for the
    /// whole 21-chip set: the host commits traces built by `generate_preprocessed`'s raw scan over
    /// `instructions`, the device commits what `gpu_generate_preprocessed` built, and
    /// `assemble_pk_with_device_merged_prep` asserts the two roots agree. Any per-chip change to
    /// *how* instructions are located — bucketing in particular — is caught here, including a
    /// bucket built in the wrong order.
    #[test]
    fn test_keygen_recursion_gpu_all_instruction_variants_match_host() {
        assert_keygen_parity(&Arc::new(
            crate::mle::machine::recursion::chips::test_programs::mixed_program(17),
        ));
    }

    #[test]
    fn test_keygen_recursion_gpu_matches_host() {
        // 100 AssertZeroExt rows → a 128-row prep next to min-height chips: exercises the
        // mixed-height commit ordering.
        assert_keygen_parity(&Arc::new(sample_program(100)));
    }
}
